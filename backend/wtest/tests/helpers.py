def make_day(day: date, tz: ZoneInfo) -> dict:
    """One daily record with every hour of that local day.

    Hours are generated by stepping through real UTC time, so DST days get
    23 or 25 hours exactly like the real API.
    """
    start = datetime(day.year, day.month, day.day, tzinfo=tz)
    end = datetime.combine(day + timedelta(days=1), datetime.min.time(), tzinfo=tz)
    hours, t, i = [], start.astimezone(timezone.utc), 0
    while t < end.astimezone(timezone.utc):
        hours.append(make_hour(t.astimezone(tz), i))
        t += timedelta(hours=1)
        i += 1

    sunrise = start.replace(hour=6, minute=30)
    sunset = start.replace(hour=16, minute=50)
    # Every value is distinct, so a field mapped to the wrong place is caught.
    return {
        "datetime": day.isoformat(),
        "datetimeEpoch": int(start.timestamp()),
        "tempmax": 60.0,
        "tempmin": 40.0,
        "temp": 51.0,
        "feelslikemax": 58.0,
        "feelslikemin": 38.0,
        "feelslike": 49.0,
        "dew": 35.0,
        "humidity": 55.0,
        "precip": 0.1,
        "precipprob": 20.0,
        "precipcover": 4.17,
        "preciptype": ["rain"],
        "snow": 0.5,
        "snowdepth": 0.2,
        "windgust": 20.0,
        "windspeed": 10.0,
        "winddir": 200.0,
        "pressure": 1012.0,
        "cloudcover": 40.0,
        "visibility": 9.5,
        "solarradiation": 120.0,
        "solarenergy": 10.4,
        "uvindex": 4.0,
        "severerisk": 15.0,
        "sunrise": "06:30:00",
        "sunriseEpoch": int(sunrise.timestamp()),
        "sunset": "16:50:00",
        "sunsetEpoch": int(sunset.timestamp()),
        "moonphase": 0.5,
        "conditions": "Rain, Partially cloudy",
        "description": "Partly cloudy with rain.",
        "icon": "rain",
        "stations": ["KNYC"],
        "source": "comb",
        "hours": hours,
    }


def make_vc_response(
    zipcode: str = "10001",
    tz_name: str = "America/New_York",
    start: date = date(2026, 11, 5),
    days: int = 2,
) -> dict:
    """A full Visual Crossing timeline response."""
    tz = ZoneInfo(tz_name)
    offset = datetime.combine(start, datetime.min.time(), tzinfo=tz).utcoffset().total_seconds() / 3600
    return {
        "queryCost": 1,
        "latitude": 40.75,
        "longitude": -73.99,
        "resolvedAddress": f"{zipcode}, United States",
        "address": zipcode,
        "timezone": tz_name,
        "tzoffset": offset,
        "days": [make_day(start + timedelta(days=n), tz) for n in range(days)],
        "alerts": [],
        "stations": {"KNYC": {"distance": 0.0, "name": "KNYC"}},
    }


def hour_epoch(year, month, day, hour, tz_name="America/New_York") -> str:
    """Epoch (as the str key the app uses) of a local hour in a timezone."""
    return str(int(datetime(year, month, day, hour, tzinfo=ZoneInfo(tz_name)).timestamp()))


class FakeStrategy(ThirdPartyWeatherAPIStrategy):
    """Stands in for Visual Crossing. Signature matches the interface exactly,
    so callers using the wrong arguments fail here just as they would for real."""

    def __init__(self, payload: Optional[dict] = None):
        self.payload = payload or make_vc_response()
        self.calls: list[dict] = []

    def fetch_map_data(self, zipcode: str, unit_group: Optional[str] = None) -> AggWeatherData:
        self.calls.append({"zipcode": zipcode, "unit_group": unit_group})
        # Use the real mapper so the service is tested with real model objects.
        from wapp.services.third_party_apis.visual_crossing import VisualCrossing
        from tests.conftest import VC_CONFIG
        return VisualCrossing(VC_CONFIG)._map_response(self.payload)
